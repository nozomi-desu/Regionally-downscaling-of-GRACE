"""Read-only export of manifest-verified frozen predictions at observed well cells."""
from pathlib import Path
import argparse
import hashlib
import json
import subprocess
import sys

import numpy as np
import pandas as pd
import xarray as xr
import yaml


def sha(path):
    """Stream a full-file SHA256."""
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for block in iter(lambda: f.read(1048576), b''):
            h.update(block)
    return h.hexdigest()


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    a = p.parse_args(); r = a.root
    sys.path.insert(0, str(r))
    from scripts.eval.common import repeat_coarse_to_fine, open_prediction_dataset, resolve_prediction_var_name
    a.output.mkdir(parents=True, exist_ok=True)
    audit = r / 'validation_rebuild/audit'
    inf = pd.read_csv(audit / 'inference_manifest.csv').query("split == 'test'")
    cp = pd.read_csv(audit / 'checkpoint_manifest.csv').set_index('paper_model')
    dm = pd.read_csv(audit / 'data_manifest.csv')
    frozen = json.loads((r / 'data_driven_alpha_beta/evaluation/frozen_manifest.json').read_text())
    configs = [yaml.safe_load((r / f'data_driven_alpha_beta/{m}/config.yaml').read_text()) for m in inf.project_model]
    paths = {c['dataset']['zarr_path'] for c in configs}
    assert len(paths) == 1
    zpath = Path(next(iter(paths)))
    z = xr.open_zarr(zpath, consolidated=True)
    # Check every dataset chunk against the final audit, including land and time masks.
    chunks = pd.read_csv(audit / 'dataset_chunk_hashes.csv')
    for row in chunks.itertuples():
        assert sha(zpath / row.path) == row.sha256, f'Dataset chunk changed: {row.path}'
    test = z.isel(time=np.flatnonzero(z.split_index.values == 2))
    times = pd.date_range('2020-01-01', '2022-12-01', freq='MS')
    assert np.array_equal(test.time.values, times.values)
    lat, lon = z.lat.values, z.lon.values
    factor = int(z.attrs['coarse_factor'])
    assert factor == 6 and all(c['dataset']['coarse_factor'] == factor for c in configs)
    assert np.allclose(np.diff(lat), .5) and np.allclose(np.diff(lon), .5)
    assert np.allclose(lat.reshape(-1, factor).mean(1), z.coarse_lat)
    assert np.allclose(lon.reshape(-1, factor).mean(1), z.coarse_lon)
    # Membership is generated by the existing project repeat operator, not geographic bins.
    coarse_ids = np.arange(z.sizes['coarse_lat'] * z.sizes['coarse_lon']).reshape(z.sizes['coarse_lat'], -1)
    membership = repeat_coarse_to_fine(coarse_ids, factor)
    wp = r / 'validation_extension_20260908/groundwater/well_monthly.csv'
    wr = dm[dm.role == 'well monthly observations'].iloc[0]
    assert sha(wp) == wr.sha256
    wells = pd.read_csv(wp).groupby('site_id').agg(lat=('lat', 'median'), lon=('lon', 'median'))
    yy = abs(lat[:, None] - wells.lat.values).argmin(0)
    xx = abs(lon[:, None] - wells.lon.values).argmin(0)
    ids = np.unique(yy * len(lon) + xx); gy, gx = np.divmod(ids, len(lon))
    indexers = dict(lat=xr.DataArray(gy, dims='cell'), lon=xr.DataArray(gx, dims='cell'))
    arr = dict(lat=lat, lon=lon, coarse_lat=z.coarse_lat.values, coarse_lon=z.coarse_lon.values,
               cell_ids=ids, coarse_ids=membership[gy, gx], land=z.land_mask.values[gy, gx],
               valid=test.valid_mask.isel(**indexers).values, times=times.values)
    meta = dict(models=[], dataset=str(zpath), dataset_chunks_verified=len(chunks),
                well_monthly_sha256=sha(wp), well_monthly_path=str(wp),
                coarse_factor=factor, coarse_operator=z.attrs['coarse_operator'],
                membership_operator='scripts.eval.common.repeat_coarse_to_fine',
                dataset_attrs=dict(z.attrs), grid_shape=[len(lat), len(lon)],
                fine_origin_centres=[float(lat[0]), float(lon[0])], code_sources={})
    for row, c in zip(inf.itertuples(), configs):
        path = Path(row.path); checkpoint = Path(row.checkpoint)
        assert sha(path) == row.sha256, f'Inference changed: {path}'
        h = sha(checkpoint)
        fr = next(x for x in frozen['models'] if x['model'] == row.project_model)
        assert h == cp.loc[row.paper_model, 'sha256'] == fr['checkpoint_sha256']
        ds = open_prediction_dataset(path)
        assert ds.attrs['checkpoint'] == str(checkpoint)
        assert int(ds.attrs['coarse_factor']) == factor and ds.attrs['split'] == 'test'
        for coord in ['lat', 'lon', 'time', 'coarse_lat', 'coarse_lon']:
            assert np.array_equal(ds[coord], test[coord]), f'Alignment: {coord}'
        assert np.array_equal(ds.valid_mask.values, test.valid_mask.values)
        for variant in ['corrected', 'raw']:
            var = resolve_prediction_var_name(ds, variant)
            assert var == f'predicted_twsa_{variant}', 'Fallback prediction disallowed'
            arr[f'{row.paper_model}_{variant}'] = ds[var].isel(**indexers).values
        meta['models'].append(dict(paper_model=row.paper_model, project_model=row.project_model,
                                   path=str(path), sha256=row.sha256, checkpoint=str(checkpoint),
                                   checkpoint_sha256=h, attrs=dict(ds.attrs)))
        ds.close()
        print('VERIFIED', row.paper_model, row.project_model, flush=True)
    bp = Path(configs[-1]['dataset']['weight_files']['beta_gradient_weight']['path'])
    assert sha(bp) == dm[dm.role == 'beta'].iloc[0].sha256
    bd = xr.open_dataset(bp)
    assert np.array_equal(bd.lat, lat) and np.array_equal(bd.lon, lon)
    arr['beta'] = bd.beta.values[gy, gx]
    meta['beta'] = dict(path=str(bp), sha256=sha(bp))
    for rel in ['scripts/eval/common.py', 'utils/mass_closure.py', 'scripts/preprocess/build_training_dataset.py',
                'scripts/eval/extract_intra3deg_sources.py']:
        meta['code_sources'][rel] = sha(r / rel)
    git = subprocess.run(['git', '-C', str(r), 'rev-parse', 'HEAD'], capture_output=True, text=True)
    meta['git_commit'] = git.stdout.strip() if git.returncode == 0 else None
    meta['export_utc'] = pd.Timestamp.now(tz='UTC').isoformat()
    np.savez_compressed(a.output / 'frozen_well_cell_predictions.npz', **arr)
    meta['bundle_sha256'] = sha(a.output / 'frozen_well_cell_predictions.npz')
    (a.output / 'source_manifest.json').write_text(json.dumps(meta, indent=2, default=lambda x: x.item() if isinstance(x, np.generic) else str(x)))


if __name__ == '__main__':
    main()
